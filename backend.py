# UPCOMING DEADLINES
# =========================================

@app.route("/internships/deadlines", methods=["GET"])
def upcoming_deadlines():

    connection = get_db_connection()

    internships = connection.execute(
        "SELECT * FROM internships"
    ).fetchall()

    connection.close()

    today = date.today()

    upcoming = []

    for internship in internships:

        # Ignore internships with no deadline
        if not internship["deadline"]:
            continue

        try:
            deadline = datetime.strptime(
                internship["deadline"],
                "%Y-%m-%d"
            ).date()
        except ValueError:
            continue

        days_left = (deadline - today).days

        if 0 <= days_left <= 7:

            internship_data = dict(internship)

            internship_data["days_left"] = days_left

            upcoming.append(internship_data)

    return jsonify(upcoming)


