from flask import Flask, request, jsonify
from flask_cors import CORS
import sqlite3
from datetime import date, datetime

from AI.pipeline import search_and_process_internships


app = Flask(__name__)
CORS(app)

DATABASE = "internflow.db"


# =========================================
# DATABASE CONNECTION
# =========================================

def get_db_connection():
    connection = sqlite3.connect(DATABASE)
    connection.row_factory = sqlite3.Row
    return connection


# =========================================
# SAVE AI INTERNSHIP RESULT
# =========================================

def save_internship(internship):

    connection = get_db_connection()
    cursor = connection.cursor()

    # Check if this internship already exists
    existing = cursor.execute("""
        SELECT id
        FROM internships
        WHERE company = ?
        AND role = ?
        AND location = ?
    """, (
        internship.get("company"),
        internship.get("role"),
        internship.get("location")
    )).fetchone()

    # Don't save duplicates
    if existing:
        connection.close()

        # Return the existing internship's ID
        return existing["id"]

    cursor.execute("""
        INSERT INTO internships
        (company, role, skills, location, stipend, deadline,
         eligibility, application_link, match_percentage)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        internship.get("company"),
        internship.get("role"),

        # Convert skills list into a string
        ", ".join(internship.get("skills", []))
        if isinstance(internship.get("skills"), list)
        else internship.get("skills"),

        internship.get("location"),
        internship.get("stipend"),
        internship.get("deadline"),
        internship.get("eligibility"),

        # AI uses application_url
        # Database uses application_link
        internship.get("application_url"),

        # Match percentage calculated by AI matching
        internship.get("match_percentage")
    ))

    # Get the ID generated by SQLite
    internship_id = cursor.lastrowid

    connection.commit()
    connection.close()

    return internship_id


