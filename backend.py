@app.route("/search-internships", methods=["POST"])
def search_internships():

    data = request.get_json()

    if not data:
        return jsonify({
            "error": "No data received"
        }), 400

    student_skills = data.get("student_skills", [])
    preferred_domain = data.get("preferred_domain", "")
    locations = data.get("locations", [])
    minimum_stipend = data.get("minimum_stipend", 0)

    if not student_skills:
        return jsonify({
            "error": "Student skills are required"
        }), 400

    if not preferred_domain:
        return jsonify({
            "error": "Preferred domain is required"
        }), 400

    if not locations:
        return jsonify({
            "error": "At least one location is required"
        }), 400

    all_results = []

    # Search separately for each selected location
    for location in locations:

        results = search_and_process_internships(
            student_skills,
            preferred_domain,
            location,
            minimum_stipend
        )

        if results:

            for internship in results:

                internship_id = save_internship(internship)

                if internship_id:
                    print(
                        f"Saved/Found in database: "
                        f"{internship.get('company')} - "
                        f"{internship.get('role')} "
                        f"(ID: {internship_id})"
                    )

                # Add database ID to the result sent to frontend
                internship["id"] = internship_id

                all_results.append(internship)

    return jsonify({
        "count": len(all_results),
        "internships": all_results
    })


